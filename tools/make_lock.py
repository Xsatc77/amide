"""Write a hash-pinned lock file for the Docker image.

    python tools/make_lock.py requirements.txt requirements.lock --exclude opencv-python
    python tools/make_lock.py requirements-watcher.txt requirements-watcher.lock

The image is linux/amd64 on Python 3.13, so the dependency set is resolved for that target (binary wheels only,
whatever machine this runs on) and every file PyPI lists for each pinned release gets a sha256 line. The image then
installs with `pip install --require-hashes --no-deps -r <lock>`: pip refuses anything not in the lock or not matching a hash.

Standard library only; it calls pip and reads pypi.org. Run it after editing the input file, review the diff, commit both.
"""
import argparse
import json
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

PLATFORMS = [
    "manylinux_2_39_x86_64", "manylinux_2_38_x86_64", "manylinux_2_36_x86_64", "manylinux_2_35_x86_64",
    "manylinux_2_34_x86_64", "manylinux_2_31_x86_64", "manylinux_2_28_x86_64", "manylinux_2_27_x86_64",
    "manylinux_2_26_x86_64", "manylinux_2_24_x86_64", "manylinux_2_17_x86_64", "manylinux2014_x86_64",
    "manylinux_2_5_x86_64", "manylinux1_x86_64", "linux_x86_64",
]


def resolve(input_file: Path, native: bool) -> dict[str, str]:
    """Name -> version for everything pip would install for linux/amd64, Python 3.13 (or, with native, on this machine)."""
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        cmd = [
            sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet",
            "--report", str(report), "-r", str(input_file),
        ]
        if not native:
            cmd += [
                "--target", str(Path(tmp) / "t"), "--only-binary=:all:", "--python-version", "3.13",
                "--implementation", "cp", "--abi", "cp313", "--abi", "abi3", "--abi", "none",
            ]
            for platform in PLATFORMS:
                cmd += ["--platform", platform]
        subprocess.run(cmd, check=True)
        data = json.loads(report.read_text(encoding="utf-8"))
    found = {}
    for item in data["install"]:
        meta = item["metadata"]
        found[meta["name"].lower().replace("_", "-").replace(".", "-")] = (meta["name"], meta["version"])
    return found


def hashes_for(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=60) as resp:  # a fixed https URL, no user input
        info = json.load(resp)
    return sorted({f["digests"]["sha256"] for f in info["urls"]})


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("output")
    ap.add_argument("--exclude", action="append", default=[], help="a package to leave out of the closure")
    ap.add_argument("--native", action="store_true", help="resolve on this machine instead of linux/amd64 3.13; only for "
                    "a set of pure-Python packages where one of them ships as a source archive (no wheel to target)")
    args = ap.parse_args()
    excluded = {e.lower().replace("_", "-") for e in args.exclude}
    resolved = resolve(Path(args.input), args.native)
    target = "the machine it was generated on (pure-Python packages only)" if args.native else "linux/amd64, Python 3.13"
    lines = [
        f"# Generated by tools/make_lock.py from {args.input} for {target}. Do not edit by hand.",
        f"# Regenerate: python tools/make_lock.py {args.input} {args.output}"
        + "".join(f" --exclude {e}" for e in args.exclude) + (" --native" if args.native else ""),
        "# Install:    pip install --require-hashes --no-deps -r " + args.output,
    ]
    for key in sorted(resolved):
        if key in excluded:
            continue
        name, version = resolved[key]
        digests = hashes_for(name, version)
        if not digests:
            sys.exit(f"no hashes for {name}=={version}")
        body = " \\\n".join(f"    --hash=sha256:{d}" for d in digests)
        lines.append(f"{name}=={version} \\\n{body}")
    Path(args.output).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {args.output}: {len(lines) - 3} packages")


if __name__ == "__main__":
    main()
